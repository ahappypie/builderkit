#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: darwin-tools-reference.sh <snapshot-dir> <output-markdown>" >&2
  exit 2
fi

SNAPSHOT_DIR=$1
OUTPUT=$2
mkdir -p "$(dirname "$OUTPUT")"
TMP=$(mktemp "${OUTPUT}.XXXXXX")
trap 'rm -f "$TMP"' EXIT

jq -er '
  def tools:
    map(select(.command != null and .command != "" and .description != ""))
    | unique_by(.name)
    | sort_by(.name);

  def cell:
    gsub("&"; "&amp;")
    | gsub("<"; "&lt;")
    | gsub(">"; "&gt;")
    | gsub("\\|"; "&#124;")
    | gsub("`"; "&#96;")
    | gsub("[\r\n\t]+"; " ");

  # Metadata can contain either one URL or a list. Nix mirror URLs and local
  # store paths are not useful browser links; choose the first public web URL.
  def web_url:
    [(if type == "array" then .[] else . end)
      | strings | select(test("^https?://[^[:space:]]+$"))]
    | .[0];

  def tool_name:
    ("`" + (.name | cell) + "`") as $label
    | (.homepage | web_url) as $url
    | if $url == null then $label
      else
        $url
        | gsub("<"; "%3C") | gsub(">"; "%3E")
        | gsub("\\|"; "%7C") | gsub("\""; "%22")
        | "[\($label)](<\(.)>)"
      end;

  def table($title; $packages):
    if $packages | length == 0 then empty
    else
      $title, "",
      "| Tool | Command | Description |",
      "| --- | --- | --- |",
      ($packages[] | "| \(tool_name) | `\(.command | cell)` | \(.description | cell) |"),
      ""
    end;

  (.home | tools) as $home
  | ($home | map(.name)) as $home_names
  | (.system | tools | map(select(.name as $name | $home_names | index($name) | not))) as $system
  | "---",
    "title: Installed tools",
    "description: Development tools included in the Builder Kit macOS bundle.",
    "---", "",
    "<!-- Generated by just docs-tools. Do not edit this file directly. -->", "",
    "## macOS", "",
    "These are the development tools and supporting utilities configured in the current macOS bundle. Exact versions depend on the bundle release you install. This is not a list of every library or internal helper used by your environment.", "",
    table("### Development tools"; $home),
    table("### Supporting system tools"; $system),
    "## Windows", "",
    "Coming soon."
' "$SNAPSHOT_DIR/package-metadata.json" > "$TMP"

mv "$TMP" "$OUTPUT"
